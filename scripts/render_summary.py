"""Generate docs/RESULTS_SUMMARY.md from results/ (no hand-typed numbers).

Verdict rules for the abstract's claims are fixed here, before results were seen:
  C1 sharper (vs deterministic and vs diffusion without physics): smaller |log grad_ratio| + |log hf_ratio|
                                          (closer to the observed sharpness; noise does not count as a win)
  C2 more physically consistent:          envelope+monotone violations of the proposed model lower than diffusion
                                          (no physics) and deterministic AND the loss-only physics model lower than
                                          diffusion (no physics), each by >= 10 % relative -> supported; lower only via guidance/projection ->
                                          partly. Violation rates of the observations are reported as reference.
  C3 accuracy vs baselines:               paired-bootstrap 95 % CI of CRPS difference (proposed - other) < 0 for
                                          all baselines -> supported; some -> partly; none -> not supported
  C4 credible drought-effect estimates:   only OBSERVATION-based checks count (revised after the red-team review,
                                          before any real-data result existed): (a) natural experiment corr > 0 and
                                          |bias| < 0.02; (b) model-vs-observed anomaly correlation with 95 % CI > 0;
                                          (c) cross-year proxy: normal-scenario forecast beats persistence and
                                          climatology on drought windows. All pass -> supported, 2 -> partly, else not;
                                          fewer than 3 runnable -> insufficient evidence. Placebos, temporal AUC and
                                          permutation test are model-input-based sanity checks, reported only.
  Tightened after red-team review 2 (only stricter, documented in docs/AUDIT.md): sharpness needs a >= 10 %
  margin; C2 capped at "partly" when the proposed model's envelope violations are < 50 % of the observations'
  (over-constraint); the natural experiment counts only with >= 10 matched pairs and max |SMD| <= 0.25; C4 is
  "not supported" when >= 2 informative observation-based checks all fail.
  C5 uncertainty-aware (calibration):     90 % coverage within [0.8, 0.95] and spread-skill in [0.7, 1.3]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
# results root: env CFVEG_RESULTS (e.g. results/full for the full-scale run), default results/
RESULTS = Path(__import__("os").environ.get("CFVEG_RESULTS", str(ROOT / "results")))
if not RESULTS.is_absolute():
    RESULTS = ROOT / RESULTS
P = "diff_phys+G+P"


def f(x, d=3):
    return "n/a" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    a = ap.parse_args()
    base = RESULTS / ("smoke" if a.smoke else "")
    default_root = RESULTS.resolve() == (ROOT / "results").resolve()
    out = (base / "RESULTS_SUMMARY.md") if (a.smoke or not default_root) else ROOT / "docs" / "RESULTS_SUMMARY.md"
    L = ["# Results summary (generated by scripts/render_summary.py — do not edit by hand)", ""]
    derived: dict = {}
    if a.smoke:
        L += ["**SMOKE RUN ON THE TEST FIXTURE — NOT A FINDING.**", ""]
    m = pd.read_csv(base / "test" / "metrics.csv")
    m = m[m.seed == 0].set_index("variant")
    data = json.loads((base / "data" / "data_summary.json").read_text()) if (base / "data" / "data_summary.json").exists() else {}
    choice = {}
    for k in ["lambda_choice", "guidance_choice"]:
        p = base / "val" / f"{k}.json"
        if p.exists():
            choice[k] = json.loads(p.read_text())
    L += ["## Setup actually run", ""]
    if data:
        L.append(f"- Locations: {data.get('n_locations')} ({data.get('split_counts')}); valid-pixel fraction "
                 f"{f(data.get('valid_pixel_frac'))}; test windows {data.get('windows_test', {}).get('n_windows')} "
                 f"(drought fraction {f(data.get('windows_test', {}).get('drought_frac'))}). "
                 f"Source: results/data/data_summary.json")
    if choice:
        lam = choice.get("lambda_choice", {}).get("lambda_scale")
        gch = choice.get("guidance_choice", {})
        lam_txt = (f"lambda scale {lam} (selected on validation)" if lam is not None else
                   "physics-loss weights NOT tuned (no lambda sweep was run; config defaults lambda_rate=1, "
                   "lambda_phen=0.5, lambda_mono=1)")
        g = gch.get("guidance_scale")
        edge = (" - the largest value of the grid, so the optimum was not identified"
                if g is not None and g == max(gch.get("candidates", [g])) else "")
        L.append(f"- {lam_txt}; guidance scale {g} selected on validation from {gch.get('candidates')}{edge}. "
                 f"Source: results/val/*.json")
    prov = base / "test" / "metrics.provenance.json"
    preset = json.loads(prov.read_text()).get("config", {}).get("preset", "?") if prov.exists() else "?"
    pw = sorted((base / "test").glob("per_window_*_s0.csv"))
    n_eval = len(pd.read_csv(pw[0])) if pw else 0
    n_eval_d = int(pd.read_csv(pw[0]).drought.sum()) if pw else 0
    L.append(f"- Preset **{preset}**, 1 seed (seed 0, no training-variance estimate); test evaluation on {n_eval} "
             f"windows ({n_eval_d} drought-labelled); ensemble members per row in results/test/metrics.csv.")
    L += ["", "## Main comparison (test split)", "",
          "| Variant | MAE | CRPS | SSIM | grad ratio | HF ratio | rate viol. | env. viol. | mono viol. |",
          "|---|---|---|---|---|---|---|---|---|"]
    for v in ["persistence", "climatology", "clim_anomaly", "det", "diff_plain", P, "diff_plain+G", "diff_plain+G+P",
              "diff_phys", "diff_phys+G", "diff_phys_no_rate+G+P", "diff_phys_no_phen+G+P", "diff_phys_no_mono+G+P"]:
        if v in m.index:
            r = m.loc[v]
            L.append(f"| {v} | {f(r.get('mae'))} | {f(r.get('crps'))} | {f(r.get('ssim'))} | {f(r.get('grad_ratio'), 2)} | "
                     f"{f(r.get('hf_ratio'), 2)} | {f(r.get('rate_frac'))} | {f(r.get('phen_frac'))} | "
                     f"{f(r.get('mono_frac'))} |")
    L += ["", "Source: results/test/metrics.csv (95 % bootstrap CIs over locations in results/test/metrics_ci.csv).", ""]
    verdicts = []
    # ---- C1 sharpness: closeness of prediction/observation sharpness ratios to 1 (|log ratio|), so that
    #      noise ("too sharp") does not count as a win (red-team M5)
    def closeness(v):
        c = abs(np.log(m.loc[v, "grad_ratio"])) + abs(np.log(m.loc[v, "hf_ratio"]))
        derived[f"sharpness_closeness_{v.replace('+', '_')}"] = float(c)
        return c
    for other, label in [("det", "the deterministic baseline"), ("diff_plain", "unconstrained diffusion")]:
        if P in m.index and other in m.index:
            better = closeness(P) < 0.9 * closeness(other)   # >= 10 % margin (tightened after review 2)
            if not better and closeness(P) < closeness(other):
                verdicts.append((f"Physics-constrained diffusion is sharper than {label} (closer to observed sharpness)",
                                 "no meaningful difference",
                                 f"closeness |log ratio| sum {f(closeness(P), 3)} vs {f(closeness(other), 3)} (< 10 % apart); "
                                 f"grad ratio {f(m.loc[P, 'grad_ratio'], 2)} vs {f(m.loc[other, 'grad_ratio'], 2)}; "
                                 f"HF ratio {f(m.loc[P, 'hf_ratio'], 2)} vs {f(m.loc[other, 'hf_ratio'], 2)}"))
                continue
            verdicts.append((f"Physics-constrained diffusion is sharper than {label} (closer to observed sharpness)",
                             "supported" if better else "not supported",
                             f"grad ratio {f(m.loc[P, 'grad_ratio'], 2)} vs {f(m.loc[other, 'grad_ratio'], 2)}; "
                             f"HF ratio {f(m.loc[P, 'hf_ratio'], 2)} vs {f(m.loc[other, 'hf_ratio'], 2)} (1 = observed)"))
    # ---- C2 physics (red-team M1): rate violations are ~0 by construction under projection, so the verdict uses
    #      envelope + monotone violations, requires the LEARNED model (loss only, no guidance/projection) to
    #      improve on unconstrained diffusion, and reports the violation rate of the observations themselves.
    def viol2(v):
        r = m.loc[v]
        return float(np.nansum([r.get("phen_frac", np.nan), r.get("mono_frac", np.nan)]))
    if P in m.index:
        others = [v for v in ["diff_plain", "det"] if v in m.index]
        # a reduction counts only if >= 10 % relative (pre-specified margin; no tiny differences)
        lower = [v for v in others if viol2(P) < 0.9 * viol2(v)]
        learned = ("diff_phys" in m.index and "diff_plain" in m.index and
                   viol2("diff_phys") < 0.9 * viol2("diff_plain"))
        verdict = ("supported" if others and len(lower) == len(others) and learned else
                   "partly supported (only via guidance/projection)" if lower else "not supported")
        # tightened after review 2: if the proposed model violates the envelope far less than the observations do,
        # the reduction reflects over-constraint (rates under projection are zero by construction) -> cap at partly
        if "observed" in m.index and verdict == "supported":
            if m.loc[P, "phen_frac"] < 0.5 * m.loc["observed", "phen_frac"]:
                verdict = ("partly supported (learned loss reduces monotone/envelope violations; guided/projected "
                           "rates are zero by construction and below the observations' own rates = over-constraint)")
        ev = "envelope / monotone violation fraction " + ", ".join(
            f"{v} {f(m.loc[v, 'phen_frac'])} / {f(m.loc[v].get('mono_frac', np.nan))}"
            for v in [P, "diff_phys"] + others if v in m.index)
        ev += ("; monotone violations are scored with the same stress perturbation used in the training loss "
               "(in-sample for the physics models)")
        if "observed" in m.index:
            obs = m.loc["observed"]
            ev += (f"; observations themselves: envelope {f(obs.get('phen_frac'))}, rate {f(obs.get('rate_frac'))} "
                   f"(fewer violations than observed = over-constraint, not physics)")
        verdicts.append(("Physics constraints make forecasts more physically consistent", verdict, ev))
    # ---- C3 accuracy
    pt = base / "test" / "paired_tests.csv"
    if pt.exists():
        t = pd.read_csv(pt)
        t = t[(t.metric == "crps") & t.other.isin(["persistence", "climatology", "clim_anomaly", "det", "diff_plain"])]
        better = t[t.hi < 0]
        verdicts.append(("Physics-constrained diffusion is more accurate (CRPS) than the baselines",
                         "supported" if len(better) == len(t) and len(t) else ("partly supported" if len(better) else "not supported"),
                         "; ".join(f"vs {r.other}: diff {f(r['diff'], 4)} [{f(r.lo, 4)}, {f(r.hi, 4)}]" for _, r in t.iterrows())
                         + " (negative = proposed better)"
                         + ("; MAE: " + "; ".join(f"vs {r.other}: {f(r['diff'], 4)} [{f(r.lo, 4)}, {f(r.hi, 4)}]"
                                                  for _, r in pd.read_csv(pt).query("metric == 'mae'").iterrows()
                                                  if r.other in ["det", "climatology", "diff_plain", "persistence"]))
                         + ". CRPS of a single deterministic forecast equals its MAE, so CRPS gains over point "
                           "baselines partly reflect being an ensemble; physics constraints cost accuracy relative "
                           "to unconstrained diffusion where that difference is positive. "
                           "Source: results/test/paired_tests.csv"))
    # ---- C4 credibility of effects
    vs = base / "validation" / "validation_summary.csv"
    if vs.exists():
        s = pd.read_csv(vs)
        s = s[s.variant == P.replace("+", "_")].set_index("metric").value
        checks = {}
        fin = lambda k: k in s and np.isfinite(s[k])  # noqa: E731  (missing/NaN -> check not run)
        # Only checks that involve OBSERVED outcomes count (red-team C1). Placebos, temporal AUC and the
        # permutation test use model inputs only and are reported as sanity checks, not as evidence.
        ne_informative = fin("n_matched") and s["n_matched"] >= 10 and fin("max_abs_smd") and s["max_abs_smd"] <= 0.25
        if fin("corr") and fin("bias_model_minus_did") and ne_informative:
            checks["natural experiment agrees (corr>0, |bias|<0.02)"] = (
                s["corr"] > 0 and abs(s["bias_model_minus_did"]) < 0.02)
        if fin("anom_corr_lo95"):
            checks["model anomaly tracks observed anomaly (corr CI > 0)"] = s["anom_corr_lo95"] > 0
        xpf = base / "validation" / "proxy_crossyear.csv"
        if xpf.exists():
            x = pd.read_csv(xpf)
            x = x[(x.variant == P.replace("+", "_")) & (x.subset == "drought windows")]
            if len(x) and {"mae_normal", "mae_persistence", "mae_climatology"} <= set(x.columns):
                r0 = x.iloc[0]
                checks["cross-year proxy: normal forecast beats persistence and climatology"] = bool(
                    r0.mae_normal < r0.mae_persistence and r0.mae_normal < r0.mae_climatology)
        n = sum(checks.values())
        ev = ", ".join(f"{k}: {'pass' if v else 'FAIL'}" for k, v in checks.items())
        ev += "; " + ", ".join(f"{k} {f(s[k])}" for k in ["corr", "bias_model_minus_did", "did_in_model_90pi",
                                                         "n_matched", "anom_corr", "anom_corr_lo95", "anom_slope"]
                               if k in s)
        ev += "; sanity only (inputs-based): " + ", ".join(f"{k} {f(s[k])}" for k in [
            "scenario_placebo_mean", "noise_placebo_mean", "temporal_auc", "perm_p_one_sided"] if k in s)
        verdicts.append(("Drought-attributable vegetation loss can be estimated credibly",
                         ("not supported (all informative observation-based checks fail"
                          + ("" if ne_informative else "; natural experiment uninformative: fewer than 10 matched pairs "
                             "or covariate imbalance SMD > 0.25") + ")")
                         if len(checks) >= 2 and n == 0 else
                         "insufficient evidence (fewer than 3 informative observation-based checks)"
                         if len(checks) < 3 else ("supported" if n == len(checks) else
                                                          ("partly supported" if n >= 2 else "not supported")),
                         ev + ". Source: results/validation/validation_summary.csv"))
    # ---- C5 calibration
    if P in m.index and "cov90" in m.columns and np.isfinite(m.loc[P, "cov90"]):
        c90, ss = m.loc[P, "cov90"], m.loc[P, "spread_skill"]
        ok = 0.8 <= c90 <= 0.95 and 0.7 <= ss <= 1.3
        verdicts.append(("Ensemble uncertainty is calibrated (uncertainty-aware estimates)",
                         "supported" if ok else ("not supported (overconfident: intervals too narrow)"
                                                  if c90 < 0.8 else "not supported"),
                         f"90 % coverage {f(c90)}, 50 % coverage {f(m.loc[P, 'cov50'])}, spread-skill {f(ss, 2)}"))
    # ---- drought-effect estimates per forecaster (guided vs unguided shows how much of the effect comes from
    #      physics guidance/projection rather than the learned weather response; red-team M3)
    effd = base / "effects"
    rows = []
    for fe in sorted(effd.glob("effects_*_s0.csv")):
        e = pd.read_csv(fe)
        d = e[e.drought == 1]
        rows.append((fe.stem.removeprefix("effects_").removesuffix("_s0"), len(e), len(d),
                     d.dDN_mean.mean() if len(d) else np.nan, e.dDN_mean.mean(),
                     e.s_N.mean(), e.s_N.quantile(0.9), e.s_D.mean(), (e.n_method == "analog").mean()))
    if rows:
        L += ["## Drought-effect estimates (test windows)", "",
              "| Forecaster | windows | drought windows | mean Δ (drought windows) | mean Δ (all) | mean s normal | "
              "p90 s normal | mean s drought | frac. analog normal |", "|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            L.append(f"| {r[0]} | {r[1]} | {r[2]} | {f(r[3], 4)} | {f(r[4], 4)} | {f(r[5], 2)} | {f(r[6], 2)} | "
                     f"{f(r[7], 2)} | {f(r[8], 2)} |")
        ne_f = base / "validation" / "natural_experiment.csv"
        if ne_f.exists():
            ne = pd.read_csv(ne_f).set_index("variant")
            obs_anom = ne["anom_mean_obs_drought"].dropna()
            did = ne["did_mean"].dropna()
            if len(obs_anom):
                oa = float(obs_anom.iloc[0])
                L.append(f"| **observed** (drought windows) | | | anomaly vs other non-drought years {f(oa, 4)}; "
                         f"matched DiD {f(float(did.iloc[0]) if len(did) else np.nan, 4)} | | | | | |")
                for v in ["diff_phys_G_P", "diff_phys", "diff_plain", "det"]:
                    if v in ne.index and np.isfinite(ne.loc[v, "anom_mean_model_drought"]) and oa != 0:
                        derived[f"anom_ratio_{v}"] = float(ne.loc[v, "anom_mean_model_drought"] / oa)
                        L.append(f"- {v}: model anomaly on drought windows {f(ne.loc[v, 'anom_mean_model_drought'], 4)} = "
                                 f"{f(ne.loc[v, 'anom_mean_model_drought'] / oa, 1)} x the observed anomaly.")
                ratios = {k.removeprefix("anom_ratio_"): v for k, v in derived.items() if k.startswith("anom_ratio_")}
                if ratios:
                    over = [k for k, v in ratios.items() if v > 1.25]
                    under = [k for k, v in ratios.items() if v < 0.8]
                    closest = min(ratios, key=lambda k: abs(np.log(max(ratios[k], 1e-6))))
                    L.append("- Generated reading (thresholds: > 1.25x over-, < 0.8x under-estimation): "
                             f"over-estimate drought losses: {', '.join(over) or 'none'}; under-estimate: "
                             f"{', '.join(under) or 'none'}; closest to the observed anomaly: {closest}. "
                             "**A model anomaly far from the observed one is model bias, not a finding.**")
        L += ["", "Δ = drought-scenario minus normal-scenario forecast (NDVI), ensemble and area mean. Compare the "
              "guided (+G+P) with the unguided physics model (diff_phys): guidance enforces the lower phenology bound "
              "only under the normal scenario, so part of a guided Δ can come from guidance. "
              "Source: results/effects/*.csv", ""]
    L += ["## Claim check (abstract hypotheses; rules fixed in scripts/render_summary.py)", "",
          "| Claim | Verdict | Evidence |", "|---|---|---|"]
    for c, v, e in verdicts:
        L.append(f"| {c} | **{v}** | {e} |")
    cav = ["", "## Statistical caveats", ""]
    if data:
        cav.append(f"- {data.get('split_counts', {}).get('test')} test locations: bootstrap intervals over so few "
                   f"location clusters are likely too narrow; p-values are from 1000 bootstrap draws (0.000 means "
                   f"< 0.001) and are not corrected for multiple comparisons.")
    effp = base / "effects" / f"effects_{P.replace('+', '_')}_s0.csv"
    if effp.exists():
        e_ = pd.read_csv(effp)
        dd_ = e_[e_.drought == 1]
        cav.append(f"- Effects: {len(e_)} test windows, of which {len(dd_)} drought-labelled at {dd_['loc'].nunique()} "
                   f"locations (years {sorted(dd_.year.unique().tolist())}).")
    gcf = base / "val" / "guidance_choice.json"
    vg = base / "val_guidance" / "metrics.csv"
    if gcf.exists() and vg.exists():
        gch = json.loads(gcf.read_text())
        gm = pd.read_csv(vg)
        cav.append(f"- Guidance scale {gch['guidance_scale']} was selected on validation from {gch['candidates']}; "
                   f"it is the largest candidate (optimum not identified). On test, guidance changes 90 % coverage "
                   f"from {f(m.loc['diff_phys+P', 'cov90']) if 'diff_phys+P' in m.index else 'n/a'} (projection only) to "
                   f"{f(m.loc[P, 'cov90'])}.")
    cav.append("- Single training seed: differences of a few thousandths between diffusion variants may be within "
               "seed-to-seed variance.")
    cav.append("- **No conclusion about drought effects is solid yet**: the drought-labelled test sample is far too "
               "small (counts above).")
    L += cav
    L += ["", "Not tested: semi-synthetic oracle (cut by project owner's instruction: no synthetic data). "
          "Classifier-free guidance ablation (not run, see PROGRESS.md).", "",
          "Limitations: see docs/LIMITATIONS.md. The drought effect is a model-based estimate, not ground truth.", ""]
    dpath = base / "derived" / "summary_derived.json"
    dpath.parent.mkdir(parents=True, exist_ok=True)
    dpath.write_text(json.dumps(derived, indent=1))
    sys.path.insert(0, str(ROOT / "src"))
    from cfveg.utils.provenance import write_provenance
    write_provenance(dpath, extra={"note": "numbers derived by scripts/render_summary.py from results/"})
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
