"""Report the v2.1 confirmation run (results/v21): merge seeds, replication summary, calibration verdict.

Calibration rule (unchanged from scripts/render_summary.py, C5): 90 % coverage in [0.8, 0.95] and spread-skill in
[0.7, 1.3]; combined over seeds: supported only if supported in every seed.

  python scripts/report_v21.py
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "v21"


def merge(src_tags: list[tuple[int, str]], dst: str) -> None:
    d = RES / dst
    d.mkdir(parents=True, exist_ok=True)
    for seed, tag in src_tags:
        s = RES / tag
        if s == d or not s.exists():
            continue
        for f in s.glob("*"):
            if f.name in ("metrics.csv", "metrics_ci.csv", "paired_tests.csv"):
                new = pd.read_csv(f)
                if (d / f.name).exists():
                    old = pd.read_csv(d / f.name)
                    new = pd.concat([old[old.seed != seed], new], ignore_index=True)
                new.to_csv(d / f.name, index=False)
            elif f.is_file() and f"_s{seed}" in f.name:
                shutil.copy2(f, d / f.name)


def c5(r) -> str:
    ok = 0.8 <= r.cov90 <= 0.95 and 0.7 <= r.spread_skill <= 1.3
    if ok:
        return "supported"
    return "not supported (" + ("overconfident" if r.cov90 < 0.8 else "underconfident" if r.cov90 > 0.95
                                else "spread-skill outside [0.7, 1.3]") + ")"


def main() -> None:
    os.environ["CFVEG_RESULTS"] = str(RES)
    merge([(1, "test_s1"), (2, "test_s2")], "test")
    merge([(0, "m32_s0"), (1, "m32_s1"), (2, "m32_s2")], "m32")
    for seed in [1, 2, 0]:
        subprocess.run([sys.executable, "scripts/render_summary.py", "--seed", str(seed)], cwd=ROOT, check=True)
    m8 = pd.read_csv(RES / "test" / "metrics.csv")
    m32 = pd.read_csv(RES / "m32" / "metrics.csv")
    meta = json.loads((ROOT / "data" / "processed_v21" / "cube" / "meta.json").read_text())
    tl = [i for i, s in zip(meta["loc_id"], meta["split"]) if s == "test"]
    L = ["# v2.1 confirmation on reserved fresh test locations (generated by scripts/report_v21.py)", "",
         f"- Test locations ({len(tl)}, never seen by any model, not part of the v2 test set): {', '.join(tl)}",
         "- Models: the v2 models (runs/v2), unchanged. Calibration (bias + spread) fitted on validation only "
         "(results/val/calib_choice.json); rule and this design committed before any result.",
         f"- Windows per seed: up to 100; 8 members for the replication rows, 32 for the calibration rows.", "",
         "## Calibration (claim C5; rule unchanged: 90 % coverage in [0.8, 0.95] and spread-skill in [0.7, 1.3])", "",
         "| Variant | members | seed | CRPS | MAE | 90 % cov. | 50 % cov. | spread-skill | verdict |",
         "|---|---|---|---|---|---|---|---|---|"]
    rows = []
    for df in (m8[m8.variant == "diff_phys+G+P"], m32):
        for r in df.itertuples():
            v = c5(r)
            if r.variant == "diff_phys+G+P+Cal":
                rows.append(v)
            L.append(f"| {r.variant} | {int(r.members)} | {r.seed} | {r.crps:.4f} | {r.mae:.4f} | {r.cov90:.3f} | "
                     f"{r.cov50:.3f} | {r.spread_skill:.2f} | {v} |")
    comb = ("supported" if rows and all(v == "supported" for v in rows) else
            "not supported" if rows and all(v.startswith("not") for v in rows) else "mixed across seeds")
    L += ["", f"**Calibrated model (diff_phys+G+P+Cal, 32 members), combined over {len(rows)} seeds: {comb}.**", "",
          "Replication of the other v2 claims on these locations (8 members, uncalibrated): "
          "results/v21/RESULTS_SUMMARY.md (seed-robustness table).", "",
          "Caveat: only the locations downloaded by the deadline were used; bootstrap intervals over so few location "
          "clusters are wide, so this is a small confirmation, not a replacement for the main test."]
    (RES / "CONFIRMATION.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
