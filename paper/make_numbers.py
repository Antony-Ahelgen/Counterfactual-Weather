"""Generate paper/numbers.tex: every result number used in the paper, as LaTeX macros, from results/ only.

Usage in LaTeX: \\R{<variant>}{<metric>} (test metrics), \\V{<variant>}{<metric>} (validation summary),
\\D{<key>} (data summary / selections). Run: python paper/make_numbers.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"


def fmt(v, d=3) -> str | None:
    try:
        v = float(v)
    except (TypeError, ValueError):
        return None
    if not np.isfinite(v):
        return None
    return f"{v:.{d}f}"


def main() -> None:
    lines = ["% AUTO-GENERATED by paper/make_numbers.py from results/ -- do not edit by hand",
             r"\makeatletter",
             r"\newcommand{\R}[2]{\@ifundefined{r@#1@#2}{\textbf{??}}{\csname r@#1@#2\endcsname}}",
             r"\newcommand{\V}[2]{\@ifundefined{v@#1@#2}{\textbf{??}}{\csname v@#1@#2\endcsname}}",
             r"\newcommand{\D}[1]{\@ifundefined{d@#1}{\textbf{??}}{\csname d@#1\endcsname}}",
             r"\makeatother"]

    def put(prefix, a, b, v, d=3):
        s = fmt(v, d)
        if s is not None:
            key = f"{prefix}@{a}@{b}" if b is not None else f"{prefix}@{a}"
            lines.append(r"\expandafter\def\csname " + key + r"\endcsname{" + s + "}")

    m = pd.read_csv(RES / "test" / "metrics.csv")
    for _, r in m.iterrows():
        v = r.variant.replace("+", "_")
        for k in ["mae", "rmse", "crps", "ssim", "grad_ratio", "hf_ratio", "rate_frac", "phen_frac", "mono_frac",
                  "range_frac", "cov50", "cov80", "cov90", "spread_skill"]:
            if k in r:
                put("r", v, k, r[k], 2 if k.endswith("ratio") or k == "spread_skill" else 3)
        if "members" in r:
            put("r", v, "members", r["members"], 0)
    ci = RES / "test" / "metrics_ci.csv"
    if ci.exists():
        for _, r in pd.read_csv(ci).iterrows():
            put("r", r.variant, f"{r.metric}lo", r.lo95)
            put("r", r.variant, f"{r.metric}hi", r.hi95)
    pt = RES / "test" / "paired_tests.csv"
    if pt.exists():
        for _, r in pd.read_csv(pt).iterrows():
            put("r", f"diff{r.other}", r.metric, r["diff"], 4)
            put("r", f"diff{r.other}", f"{r.metric}lo", r.lo, 4)
            put("r", f"diff{r.other}", f"{r.metric}hi", r.hi, 4)
    vs = RES / "validation" / "validation_summary.csv"
    if vs.exists():
        for _, r in pd.read_csv(vs).iterrows():
            dd = 0 if (r.metric.startswith("n_") or r.metric.endswith("_n")) else 3
            put("v", r.variant.split(" [")[0], r.metric + ("" if " [" not in r.variant else
                                                          ("D" if "drought" in r.variant else "A")), r.value, dd)
    ds = json.loads((RES / "data" / "data_summary.json").read_text())
    put("d", "nloc", None, ds["n_locations"], 0)
    for sp in ["train", "val", "test"]:
        put("d", f"nloc{sp}", None, ds["split_counts"].get(sp), 0)
        put("d", f"nwin{sp}", None, ds[f"windows_{sp}"]["n_windows"], 0)
        put("d", f"dfrac{sp}", None, ds[f"windows_{sp}"]["drought_frac"])
    put("d", "validfrac", None, ds["valid_pixel_frac"])
    for i, g in enumerate(["forest", "grass", "crop", "other"]):
        put("d", f"rinc{g}", None, ds["rate_bounds_inc_per_day"][i])
        put("d", f"rdec{g}", None, ds["rate_bounds_dec_per_day"][i])
    dv = RES / "derived" / "summary_derived.json"
    if dv.exists():
        for k, v in json.loads(dv.read_text()).items():
            put("d", k, None, v, 1 if k.startswith("anom_ratio") else 3)
    ne = RES / "validation" / "natural_experiment.csv"
    if ne.exists():
        n_ = pd.read_csv(ne)
        if len(n_):
            put("d", "obsanomdrought", None, n_["anom_mean_obs_drought"].iloc[0], 3)
    gc = RES / "val" / "guidance_choice.json"
    if gc.exists():
        lines.append(r"\expandafter\def\csname d@gamma\endcsname{" + f"{json.loads(gc.read_text())['guidance_scale']:g}" + "}")
    demo = RES / "counterfactual" / "demo.json"
    if demo.exists():
        dj = json.loads(demo.read_text())
        put("d", "crnratio", None, dj["crn_variance_ratio_pixel"])
        put("d", "demodelta", None, dj["area_mean_delta_crn"], 4)
    (ROOT / "paper" / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote paper/numbers.tex ({len(lines)} lines)")


if __name__ == "__main__":
    main()
